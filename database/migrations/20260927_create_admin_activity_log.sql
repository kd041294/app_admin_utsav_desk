CREATE TABLE IF NOT EXISTS activity_log (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    log_code VARCHAR(30) NOT NULL,
    admin_id BIGINT UNSIGNED NULL,
    admin_code VARCHAR(30) NULL,
    actor_name VARCHAR(150) NOT NULL,
    actor_role VARCHAR(40) NOT NULL DEFAULT 'ADMIN',
    type VARCHAR(30) NOT NULL DEFAULT 'ADMIN',
    module VARCHAR(50) NOT NULL,
    action VARCHAR(50) NOT NULL,
    subject_type VARCHAR(50) NULL,
    subject_id BIGINT UNSIGNED NULL,
    subject_name VARCHAR(200) NULL,
    description TEXT NOT NULL,
    ip_address VARCHAR(45) NULL,
    user_agent VARCHAR(500) NULL,
    device VARCHAR(200) NOT NULL DEFAULT 'Web Browser',
    severity VARCHAR(20) NOT NULL DEFAULT 'INFO',
    metadata JSON NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_activity_log_code (log_code),
    KEY idx_activity_log_created_at (created_at),
    KEY idx_activity_log_admin (admin_id, created_at),
    KEY idx_activity_log_type (type, created_at),
    KEY idx_activity_log_action (action, created_at),
    KEY idx_activity_log_module (module, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
